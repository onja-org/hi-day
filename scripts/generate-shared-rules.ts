import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Copies the backend's dependency-free rule modules into the frontend.
 *
 * Same reasoning as `generate-pricing.ts`: the backend decides, and the
 * browser needs the identical answer. Copied rather than reimplemented so a
 * rule can only be changed in one place — a form that accepts what the
 * server rejects, or a seat count the browser allows and the server refuses,
 * leaves somebody stuck with no way to see why.
 *
 * Each source must import nothing, which is what makes a verbatim copy safe.
 */
const root = join(import.meta.dirname ?? __dirname, '..');

const COPIES = [
  {
    from: 'backend/src/contact/contact-message.ts',
    to: 'frontend/src/lib/contactRules.generated.ts',
  },
  {
    from: 'backend/src/billing/seats.ts',
    to: 'frontend/src/lib/seatRules.generated.ts',
  },
];

for (const { from, to } of COPIES) {
  const body = readFileSync(join(root, from), 'utf-8');
  writeFileSync(
    join(root, to),
    `// Generated by scripts/generate-contact-rules.ts from ${from}.
// Do not edit: run \`pnpm gen:shared-rules\` instead. The backend is where
// these rules are decided, because it is what rejects a submission.

${body}`,
    'utf-8',
  );
  console.log(`wrote ${to}`);
}
