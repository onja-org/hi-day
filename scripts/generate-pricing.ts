import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  BILLING_PERIODS,
  CLOUD_BILLING_NOTE,
  monthlyPriceLabel,
  TRIAL_DAYS,
  TRIAL_PROMISE,
} from '../backend/src/billing/pricing';

/**
 * Writes the frontend's copy of the advertised prices from the backend's.
 *
 * Generated and committed rather than fetched: `/pricing` is a public page
 * that makes no backend call, and one that can fail because an internal API
 * is down is worse than the duplication this removes. A backend test fails
 * the build when the two disagree.
 *
 *   pnpm gen:pricing
 */
const target = join(
  __dirname,
  '..',
  'frontend',
  'src',
  'lib',
  'pricing.generated.ts',
);

const periods = BILLING_PERIODS.map((p) => `"${p}"`).join(', ');
const prices = BILLING_PERIODS.map(
  (p) => `  ${p}: "${monthlyPriceLabel(p)}",`,
).join('\n');
const notes = BILLING_PERIODS.map(
  (p) => `  ${p}: "${CLOUD_BILLING_NOTE[p]}",`,
).join('\n');

writeFileSync(
  target,
  `// Generated by scripts/generate-pricing.ts from backend/src/billing/pricing.ts.
// Do not edit: run \`pnpm gen:pricing\` instead. The backend is where prices
// are decided, because it is what has to match the Stripe Prices we charge.

export type BillingPeriod = ${BILLING_PERIODS.map((p) => `"${p}"`).join(' | ')};

export const BILLING_PERIODS: BillingPeriod[] = [${periods}];

/** Per person, per month — derived from the amount actually charged. */
export const CLOUD_PRICE_PER_PERSON: Record<BillingPeriod, string> = {
${prices}
};

export const CLOUD_BILLING_NOTE: Record<BillingPeriod, string> = {
${notes}
};

export const TRIAL_DAYS = ${TRIAL_DAYS};
export const TRIAL_PROMISE = ${JSON.stringify(TRIAL_PROMISE)};
`,
  'utf-8',
);

console.log(`wrote ${target}`);
